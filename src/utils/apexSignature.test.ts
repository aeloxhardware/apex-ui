import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import {
  apexGenerator, formatGeneratorLabel, parseApexVersion, resolveGenerator, type GCodeGenerator,
} from '@/components/gcodeGenerator';
import { parseGCode } from '@/components/gcodeParse';
import { readApexHeader, writeApexHeader, type ApexHeaderPayload } from './apexHeader';
import { APEX_SIGNATURE_LINE, hasApexSignature } from './apexSignature';

const sample = (name: string) => readFileSync(new URL(`./__fixtures__/${name}.gcode`, import.meta.url), 'utf8');

/** Ce que l'interface fait au chargement : parseur, bloc déchiffré (null s'il échoue), générateur final. */
async function generatorOf(text: string): Promise<GCodeGenerator | null> {
  const parsed = parseGCode(text);
  let header: ApexHeaderPayload | null = null;
  try { header = await readApexHeader(text); } catch { header = null; }
  return resolveGenerator(text, parsed.generator, header);
}

const ORCA = [
  '; generated by OrcaSlicer 2.1.0 on 2024-05-01 at 10:00:00',
  'G90', 'M82', ';TYPE:Outer wall',
  'G1 X10 Y10 Z0.2 F3000', 'G1 X20 Y10 E1 F1800', 'G1 X20 Y20 E2', 'G1 X10 Y20 E3', '',
].join('\n');

describe('hasApexSignature', () => {
  it('reconnaît la ligne exacte, avec ou sans \\r final', () => {
    expect(hasApexSignature(`${APEX_SIGNATURE_LINE}\nG21\n`)).toBe(true);
    expect(hasApexSignature(`${APEX_SIGNATURE_LINE}\r\nG21\r\n`)).toBe(true);
  });
  it('cherche dans les 40 premières lignes seulement', () => {
    const filler = (n: number) => Array.from({ length: n }, () => '; x').join('\n');
    expect(hasApexSignature(`${filler(39)}\n${APEX_SIGNATURE_LINE}\nG1 X1\n`)).toBe(true);
    expect(hasApexSignature(`${filler(40)}\n${APEX_SIGNATURE_LINE}\nG1 X1\n`)).toBe(false);
  });
  it('refuse une ligne approchante ou absente', () => {
    expect(hasApexSignature('')).toBe(false);
    expect(hasApexSignature(`${APEX_SIGNATURE_LINE} \nG21\n`)).toBe(false);
    expect(hasApexSignature(`;${APEX_SIGNATURE_LINE.slice(2)}\nG21\n`)).toBe(false);
    expect(hasApexSignature(`; 85Ejj-sV6dI-NXTGl-JiodA-0b8aZZ\nG21\n`)).toBe(false);
  });
});

describe('parseApexVersion', () => {
  it('sépare la préversion et garde le numéro tel quel', () => {
    expect(parseApexVersion('alpha-0.2.3.0.3.0.0.221')).toEqual({ prerelease: 'alpha', version: '0.2.3.0.3.0.0.221' });
    expect(parseApexVersion('0.2.3.0.3.0.0.221')).toEqual({ prerelease: null, version: '0.2.3.0.3.0.0.221' });
  });
  it('rejette ce qui n’est pas un numéro', () => {
    for (const bad of ['unknown', '', 'alpha-', 'alpha-1.x', 42, null, undefined]) expect(parseApexVersion(bad)).toBeNull();
  });
});

describe('formatGeneratorLabel', () => {
  const apex = (a: GCodeGenerator['apex']): GCodeGenerator => ({ name: 'Apex Slicer', inferred: false, apex: a });

  it('Apex, version lue', () => {
    expect(formatGeneratorLabel(apex({ version: '0.2.3.0.3.0.0.221', prerelease: 'alpha' })))
      .toEqual({ label: 'Généré par', value: 'Apex Slicer V0.2.3.0.3.0.0.221 (alpha)' });
  });
  it('Apex, version lue sans préversion', () => {
    expect(formatGeneratorLabel(apex({ version: '0.2.3', prerelease: null })).value).toBe('Apex Slicer V0.2.3');
  });
  it('Apex, bloc illisible', () => {
    expect(formatGeneratorLabel(apex({ version: null, prerelease: null, unreadable: true })))
      .toEqual({ label: 'Généré par', value: 'Apex Slicer (version illisible)' });
  });
  it('Apex, version inconnue ou absente', () => {
    expect(formatGeneratorLabel(apex({ version: null, prerelease: null })))
      .toEqual({ label: 'Généré par', value: 'Apex Slicer (version inconnue)' });
  });
  it('Apex : jamais « probablement » ni « déduit », sur les deux écrans', () => {
    for (const a of [{ version: '1.2', prerelease: 'alpha' }, { version: null, prerelease: null }, { version: null, prerelease: null, unreadable: true }]) {
      for (const screen of ['panel', 'classic'] as const) {
        const { label, value } = formatGeneratorLabel(apex(a), screen);
        expect(`${label} ${value}`).not.toMatch(/probablement|déduit/i);
      }
    }
  });
  it('hors Apex : inchangé', () => {
    const prusa: GCodeGenerator = { name: 'PrusaSlicer 2.7.1', inferred: false };
    const guess: GCodeGenerator = { name: 'PrusaSlicer ou dérivé', inferred: true };
    expect(formatGeneratorLabel(prusa)).toEqual({ label: 'Généré le plus probablement par', value: 'PrusaSlicer 2.7.1' });
    expect(formatGeneratorLabel(guess)).toEqual({ label: 'Généré le plus probablement par', value: 'PrusaSlicer ou dérivé (déduit du format)' });
    expect(formatGeneratorLabel(null)).toEqual({ label: 'Généré le plus probablement par', value: 'Inconnu' });
    expect(formatGeneratorLabel(guess, 'classic')).toEqual({ label: 'Générateur', value: 'PrusaSlicer ou dérivé (déduit)' });
    expect(formatGeneratorLabel(null, 'classic')).toEqual({ label: 'Générateur', value: '-' });
  });
});

describe('apexGenerator', () => {
  it('lit meta.apex_version', () => {
    expect(apexGenerator({ meta: { apex_version: 'alpha-0.2.3.0.3.0.0.221' } }))
      .toMatchObject({ name: 'Apex Slicer', inferred: false, apex: { version: '0.2.3.0.3.0.0.221', prerelease: 'alpha' } });
  });
  it('« unknown », absente ou sans meta : version inconnue, pas illisible', () => {
    for (const header of [{ meta: { apex_version: 'unknown' } }, { meta: {} }, {}]) {
      const g = apexGenerator(header);
      expect(g.apex).toMatchObject({ version: null, prerelease: null });
    }
  });
  it('pas de bloc : illisible', () => {
    expect(apexGenerator(null).apex?.unreadable).toBe(true);
  });
});

describe('recette : cinq G-code', () => {
  it('1. cartésien non planaire d’Apex', async () => {
    const text = sample('sample_apex_nonplanar_cartesian');
    expect(hasApexSignature(text)).toBe(true);
    const g = await generatorOf(text);
    expect(g?.inferred).toBe(false);
    expect(g?.apex?.unreadable).toBeUndefined();
    const { label, value } = formatGeneratorLabel(g);
    expect(label).toBe('Généré par');
    expect(value).toMatch(/^Apex Slicer V\d+(\.\d+)+ \(alpha\)$/);
  });

  it('2. polaire d’Apex', async () => {
    const text = sample('sample_apex_polar_4axis');
    expect(hasApexSignature(text)).toBe(true);
    const g = await generatorOf(text);
    expect(g?.inferred).toBe(false);
    expect(formatGeneratorLabel(g).value).toMatch(/^Apex Slicer V\d+(\.\d+)+ \(alpha\)$/);
  });

  it('les deux exemples portent la même version que leur bloc', async () => {
    for (const name of ['sample_apex_nonplanar_cartesian', 'sample_apex_polar_4axis']) {
      const text = sample(name);
      const raw = (await readApexHeader(text))?.meta?.apex_version as string;
      const { prerelease, version } = parseApexVersion(raw)!;
      expect(formatGeneratorLabel(await generatorOf(text)).value).toBe(`Apex Slicer V${version} (${prerelease})`);
    }
  });

  it('3. première ligne supprimée : ancien affichage, jamais « Apex Slicer »', async () => {
    for (const name of ['sample_apex_nonplanar_cartesian', 'sample_apex_polar_4axis']) {
      const text = sample(name);
      const unsigned = text.slice(text.indexOf('\n') + 1);
      expect(hasApexSignature(unsigned)).toBe(false);
      const g = await generatorOf(unsigned);
      expect(g).toEqual(parseGCode(unsigned).generator);
      const { label, value } = formatGeneratorLabel(g);
      expect(label).toBe('Généré le plus probablement par');
      expect(value).not.toContain('Apex Slicer');
    }
  });

  it('4. bloc tronqué : version illisible, sans erreur', async () => {
    for (const name of ['sample_apex_nonplanar_cartesian', 'sample_apex_polar_4axis']) {
      const text = sample(name);
      const cut = text.slice(0, text.indexOf('; apex_data:') + 150);
      const g = await generatorOf(cut);
      expect(formatGeneratorLabel(g)).toEqual({ label: 'Généré par', value: 'Apex Slicer (version illisible)' });
    }
  });

  it('4 bis. données altérées, fin de bloc présente : version illisible', async () => {
    const text = sample('sample_apex_polar_4axis').replace(/; apex_data:(.{10})/, '; apex_data:!!!!!!!!!!');
    expect(formatGeneratorLabel(await generatorOf(text)).value).toBe('Apex Slicer (version illisible)');
  });

  it('4 ter. signature sans aucun bloc : version illisible', async () => {
    expect(formatGeneratorLabel(await generatorOf(`${APEX_SIGNATURE_LINE}\n${ORCA}`)).value)
      .toBe('Apex Slicer (version illisible)');
  });

  it('version « unknown » ou absente dans un bloc lisible : version inconnue', async () => {
    for (const meta of [{ apex_version: 'unknown' }, { generator: 'Apex engine' }]) {
      const text = await writeApexHeader(`${APEX_SIGNATURE_LINE}\n${ORCA}`, { format: 1, sliced: true, meta });
      expect(formatGeneratorLabel(await generatorOf(text))).toEqual({ label: 'Généré par', value: 'Apex Slicer (version inconnue)' });
    }
  });

  it('5. G-code d’un autre slicer : inchangé', async () => {
    const g = await generatorOf(ORCA);
    expect(g).toEqual(parseGCode(ORCA).generator);
    expect(g?.apex).toBeUndefined();
    expect(formatGeneratorLabel(g)).toEqual({ label: 'Généré le plus probablement par', value: 'OrcaSlicer 2.1.0' });
  });

  it('priorité : la signature Apex l’emporte sur celle d’un autre slicer', async () => {
    const text = await writeApexHeader(`${APEX_SIGNATURE_LINE}\n${ORCA}`, { format: 1, meta: { apex_version: 'alpha-0.2.3.0.3.0.0.221' } });
    expect(parseGCode(text).generator?.name).toBe('OrcaSlicer 2.1.0');
    expect(formatGeneratorLabel(await generatorOf(text)).value).toBe('Apex Slicer V0.2.3.0.3.0.0.221 (alpha)');
  });

  it('un bloc Apex sans signature ne suffit pas', async () => {
    const text = await writeApexHeader(ORCA, { format: 1, meta: { apex_version: 'alpha-0.2.3.0.3.0.0.221' } });
    expect(formatGeneratorLabel(await generatorOf(text)).value).toBe('OrcaSlicer 2.1.0');
  });
});
