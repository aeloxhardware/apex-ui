import React, { useEffect, useRef, useState } from 'react';
import { ScanSearch } from 'lucide-react';
import type { GCodeFileInfo } from '@/hooks/use-gcode-preview';
import styles from './SliceModal.module.scss';

interface UnlayeredDetectedDialogProps {
  fileInfo: GCodeFileInfo | null;
  /** Chargement du G-code en cours : la boîte attend que le rideau de chargement se lève. */
  loading: boolean;
  /** Espace Prévisualisation affiché. */
  active: boolean;
}

/**
 * Petite boîte de dialogue affichée une fois par fichier quand le G-code chargé vient de l'Unlayered
 * Slicer (signature explicite `generated by Unlayered Slicer…`, cf. gcodeGenerator.ts), au
 * dévoilement de la Prévisualisation.
 */
export const UnlayeredDetectedDialog: React.FC<UnlayeredDetectedDialogProps> = ({ fileInfo, loading, active }) => {
  const [open, setOpen] = useState(false);
  const shownForRef = useRef<GCodeFileInfo | null>(null);

  useEffect(() => {
    if (!fileInfo || loading || !active || shownForRef.current === fileInfo) return;
    const g = fileInfo.generator;
    if (!g || g.inferred || !/^unlayered slicer/i.test(g.name)) return;
    shownForRef.current = fileInfo;
    setOpen(true);
  }, [fileInfo, loading, active]);

  // Échap / Entrée ferment la boîte.
  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape' || e.key === 'Enter') { e.preventDefault(); setOpen(false); }
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [open]);

  if (!open) return null;

  // Même rendu que la confirmation de découpe (SliceModal) : fond flouté, carte vitrée et bouton
  // séparé de la carte.
  return (
    <div className={styles.backdrop} role="dialog" aria-modal="true" aria-labelledby="unlayered-dialog-title">
      <div className={styles.modalCard} style={{ width: '360px' }}>
        <div className={styles.header}>
          <div className={styles.title} id="unlayered-dialog-title">
            <ScanSearch size={16} />
            <span>G-code Unlayered détecté</span>
          </div>
        </div>
        <div className={styles.body}>
          <p>Certaines fonctions 5 axes d'Apex ne s'appliquent qu'aux fichiers générés ici, re-slice le modèle pour en profiter.</p>
        </div>
      </div>
      <div className={styles.externalButtonsContainer} style={{ width: '360px' }}>
        <button type="button" className={styles.confirmBtn} onClick={() => setOpen(false)} autoFocus>
          OK
        </button>
      </div>
    </div>
  );
};
