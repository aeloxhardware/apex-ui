/** Ce que l'appelant fournit au départ (paramètres de createGCodeEditController). */
export type EditControllerStateHost = Pick<EditControllerState, 'camera' | 'engine' | 'canvas' | 'layer' | 'opts' | 'scene'>;

/** État partagé entre les morceaux d'initialisation : l'hôte au départ, le reste rempli au fil des morceaux. */
export function createEditControllerState(host: EditControllerStateHost): EditControllerState {
  return { ...host } as EditControllerState;
}
