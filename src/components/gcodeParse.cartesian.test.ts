import { describe, expect, it } from 'vitest';
import { parseGCode } from './gcodeParse';

// Valeurs de référence relevées sur l'ancien parseur monolithique (parité exacte vérifiée au découpage,
// 2026-11-01) : arcs G2/G3, rétractions G10/G11 et E, essuyage, pouces, M104/M106, recentrage plateau.
const SAMPLE = `; generated by PrusaSlicer 2.7
; printable_area = 0x0,200x0,200x200,0x200
; filament_diameter = 1.75
M204 P2000 T3000
M205 X10
G90
M82
G92 E0
G1 X10 Y10 Z0.2 F3000
;TYPE:External perimeter
G1 X20 Y10 E1 F1800
G2 X30 Y20 I10 J0 E2.5
G3 X20 Y30 R10 E3.5
G1 E2.5
;WIPE_START
G1 X25 Y30 E2.4
;WIPE_END
G1 E3.4
;TYPE:Internal infill
G1 X50 Y50 Z0.4 E6
G10
G1 X60 Y60 F9000
G11
M106 S128
M104 S215
G1 X70 Y60 E9
G91
G1 X1 Y1 E0.5
G90
G20
G1 X1 Y1 Z0.5 E10
G21
G28 X
G1 X5 Y5 E11
`;

describe('parseGCode cartésien', () => {
  const p = parseGCode(SAMPLE);

  it('reconnaît le générateur, le plateau et recentre les X/Y', () => {
    expect(p.kind).toBe('cartesian');
    expect(p.generator).toEqual({ name: 'PrusaSlicer 2.7', inferred: false });
    expect(p.bedCenter).toEqual({ x: 100, y: 100 });
    expect(p.moves[0].x).toBe(-90);
    expect(p.moves[1].x).toBe(-80);
  });

  it('découpe les arcs en segments et garde la ligne source', () => {
    expect(p.moves).toHaveLength(77);
    expect(p.extrudingCount).toBe(69);
    expect(p.lineIndex[2]).toBe(11);
    expect(p.lineIndex[34]).toBe(12);
  });

  it('classe rétractions, essuyage et réinjections', () => {
    expect([...p.markers.retraction]).toEqual([66, 70, 76]);
    expect([...p.markers.unretraction]).toEqual([68, 72]);
    expect([...p.markers.seam]).toEqual([0]);
    expect(p.moves[66].type).toBe('retraction');
    expect(p.moves[67].type).toBe('wipe');
    expect(p.moves[73].type).toBe('sparseInfill');
  });

  it('suit les consignes modales et les pouces', () => {
    expect(p.nozzleTempC[76]).toBe(215);
    expect(p.fanPct[76]).toBe(50);
    expect(p.usesInches).toBe(true);
    expect(p.times[76]).toBeCloseTo(3.7893, 3);
  });
});
